-- Metas de economia (RF04). O progresso não é gravado: é calculado a partir das transações
-- entre data_inicio e o prazo (integração Transações x Metas). Só o cancelamento é persistido.
CREATE TABLE metas (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome        VARCHAR(100)   NOT NULL,
    -- RNF05: valor monetário exato
    valor_alvo  NUMERIC(19, 2) NOT NULL,
    data_inicio DATE           NOT NULL,
    prazo       DATE           NOT NULL,
    cancelada   BOOLEAN        NOT NULL DEFAULT FALSE,
    CONSTRAINT metas_valor_alvo_check CHECK (valor_alvo > 0),
    CONSTRAINT metas_prazo_check CHECK (prazo >= data_inicio)
);
